-- 1. Analytics Overview
create or replace function public.analytics_overview(p_from timestamptz, p_to timestamptz)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  r jsonb;
  v_visitors bigint := 0;
  v_pageviews bigint := 0;
  v_bounce_rate numeric := 0;
  v_join_views bigint := 0;
  v_join_submits bigint := 0;
  v_single_page_sessions bigint := 0;
  v_total_pv_sessions bigint := 0;
begin
  if not public.is_admin() then
    raise exception 'not authorized' using errcode = '42501';
  end if;

  -- Visitors count (distinct non-bot sessions in window)
  select count(distinct session_id)
  into v_visitors
  from public.page_events
  where created_at >= p_from and created_at < p_to and not is_bot;

  -- Pageviews count
  select count(*)
  into v_pageviews
  from public.page_events
  where created_at >= p_from and created_at < p_to and not is_bot and event_type = 'pageview';

  -- Bounce rate: sessions with exactly 1 pageview / total sessions with >= 1 pageview
  with session_pv_counts as (
    select session_id, count(*) as pv_count
    from public.page_events
    where created_at >= p_from and created_at < p_to and not is_bot and event_type = 'pageview'
    group by session_id
  )
  select
    coalesce(count(*), 0),
    coalesce(count(*) filter (where pv_count = 1), 0)
  into v_total_pv_sessions, v_single_page_sessions
  from session_pv_counts;

  if v_total_pv_sessions > 0 then
    v_bounce_rate := round((v_single_page_sessions::numeric / v_total_pv_sessions) * 100, 1);
  else
    v_bounce_rate := 0;
  end if;

  -- Join views (sessions with pageview on /join)
  select count(distinct session_id)
  into v_join_views
  from public.page_events
  where created_at >= p_from and created_at < p_to and not is_bot
    and event_type = 'pageview' and path = '/join';

  -- Join submits
  select count(*)
  into v_join_submits
  from public.page_events
  where created_at >= p_from and created_at < p_to and not is_bot
    and (
      (event_type = 'form_step' and target = 'join:submit')
      or (event_type = 'click' and target = 'join:submit')
    );

  r := jsonb_build_object(
    'visitors', v_visitors,
    'pageviews', v_pageviews,
    'bounce_rate', v_bounce_rate,
    'join_views', v_join_views,
    'join_submits', v_join_submits
  );

  return r;
end $$;

revoke all on function public.analytics_overview(timestamptz, timestamptz) from public, anon;
grant execute on function public.analytics_overview(timestamptz, timestamptz) to authenticated;

-- 2. Analytics Timeseries (Zero-filled day buckets in Asia/Kolkata timezone)
create or replace function public.analytics_timeseries(p_from timestamptz, p_to timestamptz)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  r jsonb;
begin
  if not public.is_admin() then
    raise exception 'not authorized' using errcode = '42501';
  end if;

  with days as (
    select generate_series(
      date_trunc('day', p_from at time zone 'Asia/Kolkata'),
      date_trunc('day', (p_to - interval '1 second') at time zone 'Asia/Kolkata'),
      interval '1 day'
    ) as day_ts
  ),
  daily_stats as (
    select
      date_trunc('day', created_at at time zone 'Asia/Kolkata') as day_ts,
      count(distinct session_id) as visitors,
      count(*) filter (where event_type = 'pageview') as pageviews
    from public.page_events
    where created_at >= p_from and created_at < p_to and not is_bot
    group by 1
  )
  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'day', to_char(d.day_ts, 'YYYY-MM-DD'),
        'visitors', coalesce(s.visitors, 0),
        'pageviews', coalesce(s.pageviews, 0)
      ) order by d.day_ts asc
    ),
    '[]'::jsonb
  )
  into r
  from days d
  left join daily_stats s on d.day_ts = s.day_ts;

  return r;
end $$;

revoke all on function public.analytics_timeseries(timestamptz, timestamptz) from public, anon;
grant execute on function public.analytics_timeseries(timestamptz, timestamptz) to authenticated;

-- 3. Analytics Top Dimensions (Safe dimension whitelist)
create or replace function public.analytics_top(
  p_from timestamptz,
  p_to timestamptz,
  p_dim text,
  p_limit int default 10
)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  r jsonb;
  v_lim int := coalesce(p_limit, 10);
begin
  if not public.is_admin() then
    raise exception 'not authorized' using errcode = '42501';
  end if;

  if p_dim not in ('path', 'source', 'device', 'utm_campaign') then
    raise exception 'invalid dimension: %', p_dim using errcode = '22023';
  end if;

  with grouped as (
    select
      case p_dim
        when 'path' then coalesce(path, '/')
        when 'source' then coalesce(source, 'direct')
        when 'device' then coalesce(device, 'desktop')
        when 'utm_campaign' then coalesce(utm_campaign, 'none')
      end as label,
      count(distinct session_id) as visitors,
      count(*) filter (where event_type = 'pageview') as pageviews
    from public.page_events
    where created_at >= p_from and created_at < p_to and not is_bot
    group by 1
    order by visitors desc
    limit v_lim
  )
  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'label', label,
        'visitors', visitors,
        'pageviews', pageviews
      ) order by visitors desc
    ),
    '[]'::jsonb
  )
  into r
  from grouped;

  return r;
end $$;

revoke all on function public.analytics_top(timestamptz, timestamptz, text, int) from public, anon;
grant execute on function public.analytics_top(timestamptz, timestamptz, text, int) to authenticated;

-- 4. Analytics Interest (Impressions, Clicks, CTR & Section Engagement)
create or replace function public.analytics_interest(p_from timestamptz, p_to timestamptz)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  r jsonb;
begin
  if not public.is_admin() then
    raise exception 'not authorized' using errcode = '42501';
  end if;

  with normalized_events as (
    select
      session_id,
      event_type,
      case
        when event_type = 'click' and target in ('registration', 'gallery_open') and (meta->>'slug') is not null
          then 'event:' || (meta->>'slug')
        else coalesce(target, 'unknown')
      end as canonical_target,
      target as raw_target
    from public.page_events
    where created_at >= p_from and created_at < p_to and not is_bot
  ),
  all_targets as (
    select distinct canonical_target as target from normalized_events
    where canonical_target is not null and canonical_target != 'unknown'
    union
    select distinct raw_target as target from normalized_events
    where event_type = 'click' and raw_target is not null and raw_target != 'unknown'
  ),
  stats as (
    select
      t.target,
      count(distinct case when n.event_type = 'impression' and n.canonical_target = t.target then n.session_id end) as impressions,
      count(distinct case when n.event_type = 'click' and (n.canonical_target = t.target or n.raw_target = t.target) then n.session_id end) as clicks
    from all_targets t
    left join normalized_events n on (n.canonical_target = t.target or (n.event_type = 'click' and n.raw_target = t.target))
    group by t.target
  )
  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'target', target,
        'impressions', impressions,
        'clicks', clicks,
        'ctr', case
          when impressions > 0 then round((clicks::numeric / impressions) * 100, 1)
          else null
        end
      ) order by impressions desc, clicks desc
    ),
    '[]'::jsonb
  )
  into r
  from stats;

  return r;
end $$;

revoke all on function public.analytics_interest(timestamptz, timestamptz) from public, anon;
grant execute on function public.analytics_interest(timestamptz, timestamptz) to authenticated;

