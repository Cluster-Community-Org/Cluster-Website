-- 5. Analytics Funnel (Join form progression & drop-off analysis)
create or replace function public.analytics_funnel(p_from timestamptz, p_to timestamptz)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  r jsonb;
  v_view bigint := 0;
  v_start bigint := 0;
  v_projects bigint := 0;
  v_submit bigint := 0;
  v_abandonment jsonb;
begin
  if not public.is_admin() then
    raise exception 'not authorized' using errcode = '42501';
  end if;

  -- 1. View: distinct sessions visiting /join
  select count(distinct session_id)
  into v_view
  from public.page_events
  where created_at >= p_from and created_at < p_to and not is_bot
    and event_type = 'pageview' and path = '/join';

  -- 2. Start: sessions with join:start or any join field interaction or submit
  select count(distinct session_id)
  into v_start
  from public.page_events
  where created_at >= p_from and created_at < p_to and not is_bot
    and event_type = 'form_step'
    and (target = 'join:start' or target like 'join:field:%' or target = 'join:submit');

  -- 3. Projects: sessions reaching the projects field or submitting
  select count(distinct session_id)
  into v_projects
  from public.page_events
  where created_at >= p_from and created_at < p_to and not is_bot
    and event_type = 'form_step'
    and (target = 'join:field:projects' or target = 'join:submit');

  -- 4. Submit: sessions completing join:submit
  select count(distinct session_id)
  into v_submit
  from public.page_events
  where created_at >= p_from and created_at < p_to and not is_bot
    and event_type = 'form_step' and target = 'join:submit';

  -- 5. Abandonment by field: for sessions with start/field and no submit, find last field
  with started_sessions as (
    select distinct session_id
    from public.page_events
    where created_at >= p_from and created_at < p_to and not is_bot
      and event_type = 'form_step'
      and (target = 'join:start' or target like 'join:field:%')
  ),
  submitted_sessions as (
    select distinct session_id
    from public.page_events
    where created_at >= p_from and created_at < p_to and not is_bot
      and event_type = 'form_step' and target = 'join:submit'
  ),
  abandoned_sessions as (
    select s.session_id
    from started_sessions s
    where s.session_id not in (select session_id from submitted_sessions)
  ),
  ranked_fields as (
    select
      e.session_id,
      replace(e.target, 'join:field:', '') as field_name,
      row_number() over (partition by e.session_id order by e.created_at desc) as rn
    from public.page_events e
    inner join abandoned_sessions a on e.session_id = a.session_id
    where e.created_at >= p_from and e.created_at < p_to and not e.is_bot
      and e.event_type = 'form_step' and e.target like 'join:field:%'
  ),
  abandonment_counts as (
    select field_name, count(*) as session_count
    from ranked_fields
    where rn = 1
    group by field_name
    order by session_count desc
  )
  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'field', field_name,
        'count', session_count
      )
    ),
    '[]'::jsonb
  )
  into v_abandonment
  from abandonment_counts;

  r := jsonb_build_object(
    'steps', jsonb_build_object(
      'view', v_view,
      'start', v_start,
      'projects', v_projects,
      'submit', v_submit
    ),
    'abandonment', v_abandonment
  );

  return r;
end $$;

revoke all on function public.analytics_funnel(timestamptz, timestamptz) from public, anon;
grant execute on function public.analytics_funnel(timestamptz, timestamptz) to authenticated;

-- 6. Analytics Source Conversion (Visits vs Submitted Applicants by Traffic Channel)
create or replace function public.analytics_source_conversion(p_from timestamptz, p_to timestamptz)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  r jsonb;
begin
  if not public.is_admin() then
    raise exception 'not authorized' using errcode = '42501';
  end if;

  with event_sources as (
    select
      coalesce(source, 'direct') as source_name,
      count(distinct session_id) as visits
    from public.page_events
    where created_at >= p_from and created_at < p_to and not is_bot
    group by 1
  ),
  applicant_sources as (
    select
      coalesce(source, 'direct') as source_name,
      count(*) as applicants
    from public.applications
    where submitted_at >= p_from and submitted_at < p_to
    group by 1
  ),
  combined_sources as (
    select source_name from event_sources
    union
    select source_name from applicant_sources
  )
  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'source', c.source_name,
        'visits', coalesce(e.visits, 0),
        'applicants', coalesce(a.applicants, 0),
        'rate', case
          when coalesce(e.visits, 0) > 0 then round((coalesce(a.applicants, 0)::numeric / e.visits) * 100, 1)
          else 0
        end
      ) order by coalesce(a.applicants, 0) desc, coalesce(e.visits, 0) desc
    ),
    '[]'::jsonb
  )
  into r
  from combined_sources c
  left join event_sources e on c.source_name = e.source_name
  left join applicant_sources a on c.source_name = a.source_name;

  return r;
end $$;

revoke all on function public.analytics_source_conversion(timestamptz, timestamptz) from public, anon;
grant execute on function public.analytics_source_conversion(timestamptz, timestamptz) to authenticated;

-- 7. Analytics Applicants Breakdown (Demographics & Candidate Pipeline)
create or replace function public.analytics_applicants(p_from timestamptz, p_to timestamptz)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  r jsonb;
  v_branch jsonb;
  v_year jsonb;
  v_domain jsonb;
  v_status jsonb;
begin
  if not public.is_admin() then
    raise exception 'not authorized' using errcode = '42501';
  end if;

  -- By Branch
  select coalesce(
    jsonb_agg(
      jsonb_build_object('label', coalesce(nullif(trim(branch), ''), 'Unknown'), 'count', count(*))
      order by count(*) desc
    ),
    '[]'::jsonb
  )
  into v_branch
  from public.applications
  where submitted_at >= p_from and submitted_at < p_to
  group by 1;

  -- By Year
  select coalesce(
    jsonb_agg(
      jsonb_build_object('label', coalesce(nullif(trim(year), ''), 'Unknown'), 'count', count(*))
      order by count(*) desc
    ),
    '[]'::jsonb
  )
  into v_year
  from public.applications
  where submitted_at >= p_from and submitted_at < p_to
  group by 1;

  -- By Domain
  select coalesce(
    jsonb_agg(
      jsonb_build_object('label', coalesce(nullif(trim(domain), ''), 'Unknown'), 'count', count(*))
      order by count(*) desc
    ),
    '[]'::jsonb
  )
  into v_domain
  from public.applications
  where submitted_at >= p_from and submitted_at < p_to
  group by 1;

  -- By Status
  select coalesce(
    jsonb_agg(
      jsonb_build_object('label', coalesce(nullif(trim(status), ''), 'Pending'), 'count', count(*))
      order by count(*) desc
    ),
    '[]'::jsonb
  )
  into v_status
  from public.applications
  where submitted_at >= p_from and submitted_at < p_to
  group by 1;

  r := jsonb_build_object(
    'by_branch', v_branch,
    'by_year', v_year,
    'by_domain', v_domain,
    'by_status', v_status
  );

  return r;
end $$;

