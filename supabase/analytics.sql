grant execute on function public.analytics_applicants(timestamptz, timestamptz) to authenticated;

-- 8. Analytics Health & Errors
create or replace function public.analytics_health(p_from timestamptz, p_to timestamptz)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  r jsonb;
  v_vitals jsonb := '{}'::jsonb;
  v_js_errors bigint := 0;
  v_404_errors bigint := 0;
  v_top_404 jsonb := '[]'::jsonb;
begin
  if not public.is_admin() then
    raise exception 'not authorized' using errcode = '42501';
  end if;

  -- Core Web Vitals: calculate p75 per metric
  select coalesce(
    jsonb_object_agg(
      lower(target),
      jsonb_build_object(
        'p75', round(p75::numeric, 3),
        'count', cnt
      )
    ),
    '{}'::jsonb
  )
  into v_vitals
  from (
    select
      target,
      percentile_cont(0.75) within group (order by (meta->>'value')::numeric) as p75,
      count(*) as cnt
    from public.page_events
    where created_at >= p_from and created_at < p_to
      and event_type = 'vital'
      and (meta->>'value') is not null
    group by target
  ) v;

  -- JS errors count
  select count(*)
  into v_js_errors
  from public.page_events
  where created_at >= p_from and created_at < p_to
    and event_type = 'error'
    and target = 'js';

  -- 404 errors count
  select count(*)
  into v_404_errors
  from public.page_events
  where created_at >= p_from and created_at < p_to
    and event_type = 'error'
    and target = '404';

  -- Top 404 paths
  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'path', err_path,
        'count', cnt
      )
      order by cnt desc
    ),
    '[]'::jsonb
  )
  into v_top_404
  from (
    select
      coalesce(nullif(meta->>'path', ''), path) as err_path,
      count(*) as cnt
    from public.page_events
    where created_at >= p_from and created_at < p_to
      and event_type = 'error'
      and target = '404'
    group by 1
    order by cnt desc
    limit 20
  ) t;

  r := jsonb_build_object(
    'vitals', v_vitals,
    'js_errors', v_js_errors,
    'not_found_errors', v_404_errors,
    'errors', jsonb_build_object(
      'js', v_js_errors,
      'not_found', v_404_errors,
      'total', v_js_errors + v_404_errors
    ),
    'top_404', v_top_404
  );

  return r;
end $$;

revoke all on function public.analytics_health(timestamptz, timestamptz) from public, anon;
grant execute on function public.analytics_health(timestamptz, timestamptz) to authenticated;

-- 9. Analytics Retention Purge
create or replace function public.analytics_purge(p_days int default 90)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_deleted bigint := 0;
begin
  if not public.is_admin() then
    raise exception 'not authorized' using errcode = '42501';
  end if;

  if p_days is null or p_days <= 0 then
    raise exception 'invalid retention days: %', p_days;
  end if;

  delete from public.page_events
  where created_at < now() - (p_days || ' days')::interval;

  get diagnostics v_deleted = row_count;

  return v_deleted;
end $$;

revoke all on function public.analytics_purge(int) from public, anon;
grant execute on function public.analytics_purge(int) to authenticated;

